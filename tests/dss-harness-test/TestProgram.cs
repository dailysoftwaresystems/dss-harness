namespace DssHarness.Tests;

/// <summary>
/// The test application's entry point: this assembly is the test run, or - started by a test with a child mode - the
/// child that test controls (<see cref="TestChild"/>).
/// </summary>
/// <remarks>
/// <para>
/// A child does its work here, from <c>Main</c>, never from the module's initializer: while the initializer runs, every
/// other thread that reaches this assembly's code waits for it to finish, so a child whose work runs code of this
/// assembly on another thread - a step runner's continuation, a callback - would wait on itself for ever.
/// </para>
/// <para>
/// The test run starts as xunit's own generated entry point starts it, which the project turns off
/// (<c>XunitAutoGeneratedEntryPoint</c>) so this one can stand first.
/// </para>
/// </remarks>
internal static class TestProgram
{
    public static int Main(string[] args)
    {
        if (TestHost.ChildMode is { } mode)
        {
            // Started by a test as a child: do what the mode asks, and exit - whatever threads it left - before the test
            // framework ever starts.
            Environment.Exit(TestChild.Run(mode, args));
        }

        return args.Any(arg => arg is "-automated" or "@@")
            ? Xunit.Runner.InProc.SystemConsole.ConsoleRunner.Run(args).GetAwaiter().GetResult()
            : Xunit.MicrosoftTestingPlatform.TestPlatformTestFramework.RunAsync(args, SelfRegisteredExtensions.AddSelfRegisteredExtensions).GetAwaiter().GetResult();
    }
}
