    /// <summary>
    /// A node its file no longer holds is said gone - its body not served from lines that are not its own, its edit not
    /// written - and a whole file is no declaration an edit replaces.
    /// </summary>
    [Fact]
    public async Task ANodeGoneFromItsFile_IsSaidGone_AndAWholeFileIsNoEdit()
    {
        using var tree = await TreeAsync();
        var queries = await QueriesAsync(tree);
        var reading = Tool(tree, queries, sync: false);
        var syncing = Tool(tree, queries);
        var twice = ((GraphResolve.Found)queries.Resolve("Twice")).Card;
        var file = await AskAsync(syncing, """{"op":"edit","symbol":"docs/zoo.txt","hash":"x","text":"y"}""");
        tree.Write("src/Geometry.cs", "namespace Demo;\n");

        var shrunk = (await AskAsync(reading, """{"op":"body","symbols":["Twice"]}""")).Text;
        var gone = (await AskAsync(syncing, """{"op":"body","symbols":["Twice"]}""")).Text;
        var edit = await AskAsync(Tool(tree, queries), $$"""{"op":"edit","symbol":"Twice","hash":"#{{twice.Hash}}","text":"y"}""");
        var goneHash = await AskAsync(Tool(tree, queries), """{"op":"edit","symbol":"Twice","hash":"gone","text":"y"}""");

        Assert.Equal((GraphToolOutcome.Answered, "'docs/zoo.txt' is a whole file, and no declaration an edit replaces: edit a declaration in it"), (file.Outcome, file.Text));
        Assert.Equal("'Demo.Geometry.Twice' is not at src/Geometry.cs:16-19 now: the file holds 1 line(s); find it again", shrunk);
        Assert.Equal("'Demo.Geometry.Twice' is no longer declared in 'src/Geometry.cs'", gone);
        Assert.Equal((GraphToolOutcome.Answered, "'Demo.Geometry.Twice' is no longer declared in 'src/Geometry.cs': find it again"), (edit.Outcome, edit.Text));
        Assert.Equal((GraphToolOutcome.Answered, edit.Text), (goneHash.Outcome, goneHash.Text));
        Assert.Equal("namespace Demo;\n", File.ReadAllText(Path.Combine(tree.Tree, "src", "Geometry.cs")));
    }

