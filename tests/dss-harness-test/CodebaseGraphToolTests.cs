        Assert.Equal(write, JsonSchemaSubset.Problems(schema, JsonNode.Parse("""{"op":"edit","symbol":"a","hash":"b","text":"c"}""")).Count == 0);
        Assert.Equal(narrow, JsonSchemaSubset.Problems(schema, JsonNode.Parse("""{"op":"wholeFile","path":"a","reason":"b"}""")).Count == 0);
        Assert.Empty(JsonSchemaSubset.Problems(schema, JsonNode.Parse("""{"op":"find","query":"x"}""")));

        using var tree = await TreeAsync();
        var refused = await AskAsync(Tool(tree, await QueriesAsync(tree)), """{"op":"edit","symbol":"Twice","hash":"b","text":"c"}""", given);

        Assert.Equal(write ? GraphToolOutcome.Answered : GraphToolOutcome.Usage, refused.Outcome);
        Assert.Equal(!write, refused.Text.StartsWith($"op 'edit' is not one this step may use: {ops.Replace(",", ", ", StringComparison.Ordinal)}", StringComparison.Ordinal));
