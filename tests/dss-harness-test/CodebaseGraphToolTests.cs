    /// <summary>
    /// Every line that names a node carries <c>path:start-end #hash</c>, and reading that range of the file gives the lines
    /// whose digest the hash begins: an agent reads exactly a node's lines with the reader it has.
    /// </summary>
    [Fact]
    public async Task EveryLineNamingANode_CarriesARangeAndAHash_ThatTheRangeReadBackGives()
    {
        using var tree = await TreeAsync();
        var tool = Tool(tree, await QueriesAsync(tree));
        var answers = new StringBuilder();

        foreach (var ask in new[]
        {
            """{"op":"find","query":"Area"}""",
            """{"op":"find","query":"Geometry"}""",
            """{"op":"node","symbol":"Total"}""",
            """{"op":"related","symbol":"Twice","relation":"callees","depth":2}""",
            """{"op":"outline","path":"src/Shapes.cs"}""",
            """{"op":"outline","path":"src/Geometry.cs"}""",
            """{"op":"outline","path":"tests/GeometryTests.cs"}""",
            """{"op":"outline","symbol":"Circle"}""",
            """{"op":"body","symbols":["Total","Circle"]}""",
        })
        {
            answers.Append((await AskAsync(tool, ask)).Text).Append('\n');
        }

        var ranges = Range().Matches(answers.ToString());

        Assert.True(ranges.Count > 20, $"only {ranges.Count} ranges were named");

        foreach (Match range in ranges)
        {
            var lines = CodeFileText.Lines(File.ReadAllText(Path.Combine(tree.Tree, range.Groups["path"].Value)));
            var start = int.Parse(range.Groups["start"].Value, System.Globalization.CultureInfo.InvariantCulture);
            var end = int.Parse(range.Groups["end"].Value, System.Globalization.CultureInfo.InvariantCulture);

            Assert.Equal(range.Groups["hash"].Value, CodeGraphIds.Digest(lines, start, end)[..8]);
        }
    }

